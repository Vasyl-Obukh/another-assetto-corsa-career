// The shipped provenance catalogue: every folder ID we can name, and what it is.
//
// Authored data, and only data - nothing here is inferred. Folder prefixes were
// tried and dropped: they miss as often as they hit, an older mod may predate its
// team's naming convention, and mods squat on Kunos-looking names outright, so
// ks_ferrari_296_gt3 is by First Studio Race and Kunos never made one. AC's own
// ui/dlc_ui_car.json marker gets copied verbatim by mods for the same reason.
//
// An ID in none of these records is a mod with no maker, which is the honest
// answer. `npm run catalogue -- --verify` lists what is still unclassified, and
// `npm run catalogue` drafts DLC rows from AC's markers for review.

